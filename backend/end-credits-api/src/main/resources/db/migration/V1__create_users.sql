CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_users_username_length CHECK (char_length(username) BETWEEN 3 AND 30),
    CONSTRAINT ck_users_email_length CHECK (char_length(email) BETWEEN 3 AND 255),
    CONSTRAINT ck_users_password_hash_not_blank CHECK (char_length(password_hash) > 0)
);

CREATE UNIQUE INDEX ux_users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));
