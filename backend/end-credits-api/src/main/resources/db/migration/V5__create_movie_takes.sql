CREATE TABLE movie_takes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tmdb_id BIGINT NOT NULL,
    body VARCHAR(1200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_movie_takes_user_tmdb UNIQUE (user_id, tmdb_id),
    CONSTRAINT ck_movie_takes_body_not_blank CHECK (char_length(trim(body)) > 0)
);

CREATE INDEX ix_movie_takes_user_updated_at ON movie_takes (user_id, updated_at DESC);
