CREATE TABLE user_movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tmdb_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    release_date VARCHAR(10),
    poster_path VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'WATCHLIST',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_user_movies_user_tmdb UNIQUE (user_id, tmdb_id),
    CONSTRAINT ck_user_movies_status CHECK (status IN ('WATCHLIST', 'WATCHING', 'FINISHED')),
    CONSTRAINT ck_user_movies_title_not_blank CHECK (char_length(title) > 0)
);

CREATE INDEX ix_user_movies_user_created_at ON user_movies (user_id, created_at DESC);
